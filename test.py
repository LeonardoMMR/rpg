def funcao_soma(v1, v2):
    return v1 + v2

def funcao_subtracao(v1, v2):
    return v1 - v2
 
def funcao_multiplicacao(v1, v2):
    return v1 * v2

def funcao_divisao(v1, v2):
    return v1 / v2  

def funcao_potenciacao(v1, v2):
    return v1 ** v2

def funcao_radiciacao(v1, v2):
    return v1 ** (1/v2)

print(funcao_soma(10, 10))
print(funcao_multiplicacao(2,2))
print(funcao_subtracao(10, 5))
print(funcao_divisao(9, 3))
print(funcao_potenciacao(10, 2))
print(funcao_radiciacao(81, 2))
print(funcao_radiciacao(10, 2))